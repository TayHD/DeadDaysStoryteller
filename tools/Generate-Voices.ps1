# Dead Days: Storyteller - voice pack generator (ElevenLabs + ffmpeg).
#
#   .\Generate-Voices.ps1 -ListVoices        Voices on your ElevenLabs account (free).
#   .\Generate-Voices.ps1 -Plan              Count lines/characters/files to generate (free).
#   .\Generate-Voices.ps1 -Generate          Generate every missing line (uses credits).
#   .\Generate-Voices.ps1 -Generate -Limit 20  Generate a small batch to test voices.
#   .\Generate-Voices.ps1 -Rebuild           Rewrite manifest + sound scripts from files on disk.
#
# Input: Zomboid/Lua/DeadDaysStory_voicelines.txt, written by the mod at server
# start (or Journal > Log > admin "Export voices").
# Voices: tools/voices.json maps archetype/role + gender to an ElevenLabs voice id.
# The API key is read from the ELEVENLABS_API_KEY environment variable.

param(
    [switch]$ListVoices,
    [switch]$Plan,
    [switch]$Generate,
    [switch]$Rebuild,
    [switch]$AddLibrary,
    [switch]$AccountOnly,
    [switch]$Prune,
    [int]$Limit = 0,
    [string]$Role = "",
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$mod = Join-Path $root 'data\mods\DeadDaysStoryteller'
$tsv = Join-Path $root 'data\Lua\DeadDaysStory_voicelines.txt'
$configPath = Join-Path $PSScriptRoot 'voices.json'
$ffmpeg = Join-Path $PSScriptRoot 'ffmpeg\ffmpeg.exe'
$voiceDir = Join-Path $mod 'common\media\sound\dds_voice'
$scriptOut = Join-Path $mod '42\media\scripts\DeadDaysStory_voices.txt'
$manifestOut = Join-Path $mod '42\media\lua\shared\DeadDaysStory\DDS_VoiceManifest.lua'

function Get-ApiKey {
    $k = [Environment]::GetEnvironmentVariable('ELEVENLABS_API_KEY', 'Process')
    if (-not $k) { $k = [Environment]::GetEnvironmentVariable('ELEVENLABS_API_KEY', 'User') }
    if (-not $k) { throw 'ELEVENLABS_API_KEY is not set.' }
    return $k
}

if ($ListVoices) {
    $key = Get-ApiKey
    $r = Invoke-RestMethod -Uri 'https://api.elevenlabs.io/v1/voices' -Headers @{ 'xi-api-key' = $key }
    $r.voices | ForEach-Object {
        $l = $_.labels
        [pscustomobject]@{
            name = $_.name; voice_id = $_.voice_id; category = $_.category
            gender = $l.gender; age = $l.age; accent = $l.accent; use = $l.use_case; description = $l.description
        }
    } | Sort-Object gender, name | Format-Table -AutoSize | Out-String -Width 260
    return
}

function Read-Lines {
    if (-not (Test-Path $tsv)) { throw "No export at $tsv. Start the server once (it exports on start)." }
    $rows = Import-Csv -Path $tsv -Delimiter "`t"
    if ($Role) { $rows = $rows | Where-Object { $_.role -eq $Role } }
    return $rows
}

function Read-Config {
    if (-not (Test-Path $configPath)) { throw "Missing $configPath" }
    return Get-Content $configPath -Raw | ConvertFrom-Json
}

function Voice-For($cfg, $row) {
    $map = $cfg.voices
    $candidates = @()
    if ($row.arch -and $row.arch -ne '-') {
        $candidates += "$($row.role).$($row.arch).$($row.gender)"
        # "leader" lines are spoken by whoever runs the settlement: the contact or the medic.
        $candidates += "contact.$($row.arch).$($row.gender)"
        $candidates += "doctor.$($row.arch).$($row.gender)"
    }
    $candidates += "$($row.role).$($row.gender)"
    foreach ($c in $candidates) {
        $p = $map.PSObject.Properties[$c]
        if ($p -and $p.Value) { return $p.Value }
    }
    $d = $cfg.default.PSObject.Properties[$row.gender]
    if ($d) { return $d.Value }
    return $null
}

function Write-Outputs {
    $files = @()
    if (Test-Path $voiceDir) { $files = Get-ChildItem $voiceDir -Filter *.ogg | Sort-Object Name }
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('module Base')
    [void]$sb.AppendLine('{')
    foreach ($f in $files) {
        $id = $f.BaseName
        [void]$sb.AppendLine("    sound DDSVoice_$id")
        [void]$sb.AppendLine('    {')
        [void]$sb.AppendLine('        category = UI,')
        [void]$sb.AppendLine('        is3D = false,')
        [void]$sb.AppendLine('        clip')
        [void]$sb.AppendLine('        {')
        [void]$sb.AppendLine("            file = media/sound/dds_voice/$($f.Name),")
        [void]$sb.AppendLine('            volume = 0.9,')
        [void]$sb.AppendLine('        }')
        [void]$sb.AppendLine('    }')
    }
    [void]$sb.AppendLine('}')
    [IO.File]::WriteAllText($scriptOut, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

    $lua = New-Object System.Text.StringBuilder
    [void]$lua.AppendLine('-- Generated by tools/Generate-Voices.ps1. Lines that have audio in the voice pack.')
    [void]$lua.AppendLine('DDS = DDS or {}')
    [void]$lua.AppendLine('DDS.VoiceManifest = {')
    foreach ($f in $files) { [void]$lua.AppendLine("    [`"$($f.BaseName)`"] = true,") }
    [void]$lua.AppendLine('}')
    [IO.File]::WriteAllText($manifestOut, $lua.ToString(), (New-Object System.Text.UTF8Encoding($false)))
    $mb = ($files | Measure-Object Length -Sum).Sum / 1MB
    Write-Host ("Voice pack: {0} files, {1:N1} MB. Manifest and sound scripts written." -f $files.Count, $mb)
}

if ($Rebuild) { Write-Outputs; return }

if ($Prune) {
    # Remove audio for lines that are no longer in the exported script.
    $ids = @{}
    Import-Csv -Path $tsv -Delimiter "`t" | ForEach-Object { $ids[$_.id] = $true }
    $removed = 0
    foreach ($f in Get-ChildItem $voiceDir -Filter *.ogg) {
        if (-not $ids[$f.BaseName]) { Remove-Item -LiteralPath $f.FullName -Force; $removed++ }
    }
    Write-Host "Pruned $removed files no longer in the script."
    Write-Outputs
    return
}

if ($AddLibrary) {
    $key = Get-ApiKey
    $cfg = Read-Config
    $have = (Invoke-RestMethod -Uri 'https://api.elevenlabs.io/v1/voices' -Headers @{ 'xi-api-key' = $key }).voices | ForEach-Object { $_.voice_id }
    foreach ($p in $cfg.library_to_add.PSObject.Properties) {
        $v = $p.Value
        if ($have -contains $v.voice_id) { Write-Host "Already on account: $($p.Name)"; continue }
        $body = @{ new_name = "DD - " + $p.Name } | ConvertTo-Json
        try {
            Invoke-RestMethod -Method Post -Uri "https://api.elevenlabs.io/v1/voices/add/$($v.owner)/$($v.voice_id)" `
                -Headers @{ 'xi-api-key' = $key } -ContentType 'application/json' -Body $body | Out-Null
            Write-Host "Added: $($p.Name)"
        } catch { Write-Warning "Could not add $($p.Name): $($_.Exception.Message)" }
    }
    return
}

$rows = @(Read-Lines)

if ($Plan) {
    $cfg = $null
    if (Test-Path $configPath) { $cfg = Read-Config }
    $todo = $rows | Where-Object { $Force -or -not (Test-Path (Join-Path $voiceDir "$($_.id).ogg")) }
    $chars = ($todo | ForEach-Object { $_.text.Length } | Measure-Object -Sum).Sum
    Write-Host ("Lines exported: {0}. Still to generate: {1}. Characters: {2:N0}." -f $rows.Count, @($todo).Count, $chars)
    Write-Host ("Estimated pack size: ~{0:N0} MB (about 3 KB per second of speech)." -f ($chars / 14 * 3 / 1024))
    $rows | Group-Object role | Sort-Object Count -Descending | ForEach-Object {
        $c = ($_.Group | ForEach-Object { $_.text.Length } | Measure-Object -Sum).Sum
        "{0,-18} {1,5} lines {2,8:N0} chars" -f $_.Name, $_.Count, $c
    }
    if ($cfg) {
        $missing = $rows | Where-Object { -not (Voice-For $cfg $_) } | Group-Object { "$($_.arch).$($_.gender)" }
        if ($missing) { Write-Host 'No voice assigned for:'; $missing | ForEach-Object { '  ' + $_.Name } }
    }
    return
}

if ($Generate) {
    $key = Get-ApiKey
    $cfg = Read-Config
    if (-not (Test-Path $ffmpeg)) { throw "ffmpeg not found at $ffmpeg" }
    New-Item -ItemType Directory -Force $voiceDir | Out-Null
    $tmp = Join-Path $env:TEMP 'dds_voice_tmp.pcm'
    $model = if ($cfg.model_id) { $cfg.model_id } else { 'eleven_multilingual_v2' }
    $settings = if ($cfg.voice_settings) { $cfg.voice_settings } else { @{ stability = 0.5; similarity_boost = 0.75; style = 0.0 } }
    $accountVoices = $null
    if ($AccountOnly) {
        $accountVoices = (Invoke-RestMethod -Uri 'https://api.elevenlabs.io/v1/voices' -Headers @{ 'xi-api-key' = $key }).voices | ForEach-Object { $_.voice_id }
    }
    $done = 0; $spent = 0; $skipped = 0; $deferred = 0
    foreach ($row in $rows) {
        if ($Limit -gt 0 -and $done -ge $Limit) { break }
        $out = Join-Path $voiceDir "$($row.id).ogg"
        if ((Test-Path $out) -and -not $Force) { $skipped++; continue }
        $voice = Voice-For $cfg $row
        if (-not $voice) { Write-Warning "No voice for $($row.role)/$($row.arch)/$($row.gender) - skipping $($row.id)"; continue }
        if ($accountVoices -and -not ($accountVoices -contains $voice)) { $deferred++; continue }
        $body = @{ text = $row.text; model_id = $model; voice_settings = $settings } | ConvertTo-Json -Depth 4
        $uri = "https://api.elevenlabs.io/v1/text-to-speech/$voice`?output_format=pcm_22050"
        $ok = $false
        for ($attempt = 1; $attempt -le 4 -and -not $ok; $attempt++) {
            try {
                Invoke-WebRequest -Method Post -Uri $uri -Headers @{ 'xi-api-key' = $key } -ContentType 'application/json' `
                    -Body ([Text.Encoding]::UTF8.GetBytes($body)) -OutFile $tmp -UseBasicParsing | Out-Null
                $ok = $true
            } catch {
                $code = $_.Exception.Response.StatusCode.value__
                if ($code -eq 401 -or $code -eq 402 -or $code -eq 403) { throw "ElevenLabs refused the request ($code): check the key and your remaining credits." }
                Start-Sleep -Seconds ([Math]::Pow(2, $attempt))
            }
        }
        if (-not $ok) { Write-Warning "Failed after retries: $($row.id) ($($row.origin))"; continue }
        $filter = 'loudnorm=I=-18:TP=-2'
        if ($row.radio -eq '1') { $filter = 'highpass=f=320,lowpass=f=3300,acompressor=threshold=-18dB:ratio=4,volume=1.4,loudnorm=I=-18:TP=-2' }
        & $ffmpeg -hide_banner -loglevel error -y -f s16le -ar 22050 -ac 1 -i $tmp -af $filter -ar 22050 -ac 1 -c:a libvorbis -q:a 0 $out
        if ($LASTEXITCODE -ne 0) { Write-Warning "ffmpeg failed for $($row.id)"; continue }
        $done++; $spent += $row.text.Length
        if ($done % 25 -eq 0) { Write-Host ("  {0} generated, {1:N0} characters so far..." -f $done, $spent) }
    }
    if (Test-Path $tmp) { Remove-Item $tmp -Force }
    Write-Host ("Generated {0} lines ({1:N0} characters). Skipped {2} already done. Deferred {3} (voice not on account yet)." -f $done, $spent, $skipped, $deferred)
    Write-Outputs
    return
}

Get-Help $MyInvocation.MyCommand.Path
